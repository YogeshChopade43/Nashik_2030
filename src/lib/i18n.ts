// English / Marathi UI. Strings are keyed by their English text, so English needs no table and a
// missing Marathi entry falls back to English (i18n.test.ts checks that none are missing).
// Place names are data, not UI: Marathi names come only from OpenStreetMap, never transliterated.

export type Lang = 'en' | 'mr';

let lang: Lang = 'en';
export const getLang = () => lang;
export function setLang(l: Lang) {
  lang = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

/** BCP 47 locale for Intl formatting; Latin digits in both languages. */
export const locale = () => (lang === 'mr' ? 'mr-IN-u-nu-latn' : 'en-IN');

export function t(s: string, vars?: Record<string, string | number>): string {
  const out = lang === 'mr' ? MR[s] ?? s : s;
  return vars ? out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : out;
}

const DEVANAGARI = /[ऀ-ॿ]/;

/** Marathi name from OSM: `name:mr`, else the local-script name when it is Devanagari. */
export const marathiName = (p: { name_local: string | null; tags: Record<string, string> }): string | null =>
  p.tags['name:mr'] ?? (p.name_local && DEVANAGARI.test(p.name_local) ? p.name_local : null);

/** Name in the current language, falling back to the English/OSM name. */
export const localName = (p: { name: string | null; name_local: string | null; tags: Record<string, string> }) =>
  (lang === 'mr' ? marathiName(p) : null) ?? p.name;

